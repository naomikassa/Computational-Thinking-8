# ###############################################
# ### SETUP ###
import turtle
# ###############################################

t = turtle.Turtle()
t.penup()
t.goto(-100, -100)
t.color("purple")
t.pendown()

for i in range(10000000):
    t.forward(10)
    t.left(10)




# ###############################################
# ### ENDING ###
turtle.exitonclick()
